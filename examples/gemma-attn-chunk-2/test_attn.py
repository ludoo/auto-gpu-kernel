# --- seeded sequences on a paged cache ---------------------------------


class _Seq:

  def __init__(self, total, keep_from, q_from, q_all, table):
    assert keep_from % PAGE == 0
    self.total = total
    self.keep_from = keep_from
    self.q_from = q_from
    self.q_all = q_all
    self.table = table

  def q(self, start, end):
    assert start >= self.q_from and end <= self.total, (start, end)
    return self.q_all[start - self.q_from:end - self.q_from]


class _Cache:
  """Several sequences on one paged bf16 cache, physical pages a random
  permutation so every call's `kv_indices` is a real gather. `meta`
  builds one launch's metadata for `(seq_index, rows, end)` calls —
  the last `rows` positions up to `end` — in the engine's shape plus
  `pos_base`."""

  def __init__(self, kind, pages, seqs):
    self.kind = kind
    self.g = KINDS[kind]
    self.pages = pages
    self.seqs = seqs

  def gather_range(self, si, rows, end):
    s = self.seqs[si]
    first = max(0, end - rows - WINDOW) // PAGE if self.kind == 'sliding' else 0
    assert first * PAGE >= s.keep_from, (first, s.keep_from)
    used = (end + PAGE - 1) // PAGE
    return first, used, end - (used - 1) * PAGE

  def meta(self, calls):
    qo, kvp, idx, last, base = [0], [0], [], [], []
    for si, rows, end in calls:
      first, used, last_len = self.gather_range(si, rows, end)
      qo.append(qo[-1] + rows)
      idx.append(self.seqs[si].table[first:used])
      kvp.append(kvp[-1] + used - first)
      last.append(last_len)
      base.append(first * PAGE)
    i32 = lambda x: torch.tensor(x, dtype=torch.int32, device='cuda'
                                )  # noqa: E731
    return (i32(qo), i32(kvp), torch.cat(idx).to(torch.int32), i32(last),
            i32(base))

  def q(self, calls):
    return torch.cat(
        [self.seqs[si].q(end - rows, end) for si, rows, end in calls])

  def dense_kv(self, si, start, end):
    s = self.seqs[si]
    pos = torch.arange(start, end, device='cuda')
    phys = s.table[pos // PAGE].long()
    slot = pos % PAGE
    return self.pages[phys, 0, slot], self.pages[phys, 1, slot]


def make_cache(kind, seed, specs):
  g = KINDS[kind]
  gen = torch.Generator(device='cuda').manual_seed(seed * 7919 + len(specs))
  specs = [s if len(s) == 3 else (s[0], s[1], s[1]) for s in specs]
  n_pages = [(t + PAGE - 1) // PAGE - k // PAGE for t, k, _ in specs]
  n_phys = sum(n_pages)
  perm = torch.randperm(n_phys, device='cuda', generator=gen).to(torch.int32)
  pages = (torch.randn(n_phys, 2, PAGE, g['kv_heads'], g['head_dim'],
                       device='cuda', generator=gen) * SCALE).bfloat16()
  seqs = []
  off = 0
  for (total, keep_from, q_from), n in zip(specs, n_pages):
    q_all = (torch.randn(total - q_from, HEADS, g['head_dim'], device='cuda',
                         generator=gen) * SCALE).bfloat16()
    table = torch.full(((total + PAGE - 1) // PAGE,), -1, dtype=torch.int32,
                       device='cuda')
    table[keep_from // PAGE:] = perm[off:off + n]
    off += n
    seqs.append(_Seq(total, keep_from, q_from, q_all, table))
  return _Cache(kind, pages, seqs)


# --- the fp32 reference and the wheel ----------------------------------


def reference_rows(cache, si, start, end):
  g = cache.g
  nkv, d, wl = g['kv_heads'], g['head_dim'], g['window_left']
  group = HEADS // nkv
  lo = 0 if wl < 0 else max(0, start - wl)
  k, v = cache.dense_kv(si, lo, end)
  k, v = k.float(), v.float()
  q = cache.seqs[si].q(start, end).float()
  R = end - start
  s = torch.einsum('rhgd,lhd->rhgl', q.view(R, nkv, group, d), k)
  pos = torch.arange(start, end, device='cuda')[:, None]
  key = torch.arange(lo, end, device='cuda')[None, :]
  allowed = key <= pos
  if wl >= 0:
    allowed &= key >= pos - wl
  s = s.masked_fill(~allowed[:, None, None, :], float('-inf'))
  p = torch.softmax(s, dim=-1)
  o = torch.einsum('rhgl,lhd->rhgd', p, v)
  return o.reshape(R, HEADS, d).to(torch.bfloat16)


_WHEEL = {}


def wheel_rows(cache, calls):
  from reference import _new_wrapper  # noqa: PLC0415
  if 'w' not in _WHEEL:
    _WHEEL['w'] = _new_wrapper()
  wr = _WHEEL['w']
  g = cache.g
  qo, kvp, idx, last, _ = cache.meta(calls)
  wr.plan(qo, kvp, idx, last, HEADS, g['kv_heads'], g['head_dim'], PAGE,
          causal=True, sm_scale=1.0, window_left=g['window_left'],
          q_data_type=torch.bfloat16, kv_data_type=torch.bfloat16)
  return wr.run(cache.q(calls), cache.pages)


# --- the arms ----------------------------------------------------------


def _call(cache, calls):
  from gemma_attn import gemma_attention  # noqa: PLC0415
  q = cache.q(calls)
  meta = cache.meta(calls)
  out = torch.empty_like(q)
  gemma_attention(q, cache.pages, *meta, cache.g['window_left'], out)
  torch.cuda.synchronize()
  return out


def _assert_bitwise(out, ref, label):
  if torch.equal(out, ref):
    return
  diff = out != ref
  rows = torch.nonzero(diff.flatten(1).any(1)).flatten().tolist()
  raise AssertionError(
      f'{label}: {int(diff.sum())} elements differ in {len(rows)} rows '
      f'(first rows {rows[:8]}; max |delta| '
      f'{(out.float() - ref.float()).abs().max().item():.3e})')


def _assert_near_fp32(cache, out, si, start, end, label):
  ref = reference_rows(cache, si, start, end).float()
  wheel = wheel_rows(cache, [(si, end - start, end)]).float()
  rel = ((out.float() - ref).norm() / ref.norm()).item()
  rel_w = ((wheel - ref).norm() / ref.norm()).item()
  assert rel <= 2.0 * rel_w + 1e-6, (
      f'{label}: rel-L2 vs fp32 {rel:.3e}, the wheel {rel_w:.3e}')


