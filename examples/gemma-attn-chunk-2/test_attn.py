# --- the image block mask, task next.121 --------------------------------
#
# The sliding kind's one custom mask: inside an image's absolute span
# `[lo, hi)` keys are bidirectional, under the window; everywhere else
# the row is plain causal. It enters the kernel as per-sequence span
# metadata — `span_indptr` int32 [n + 1], `span_bounds` int32 [S, 2],
# absolute — and drops into `ok` without touching the fold, so (a) a
# text row's bytes do not depend on whether a span rode in its launch,
# (b) chunking on a grid that never straddles a span is bitwise
# invariant exactly as the text path is, and (c) a launch with empty
# span tensors is bit-for-bit the launch without them. The correctness
# comparator is the wheel under its packed custom mask (the path this
# replaces), the predicate `image_block_mask_bool` documents.

SPANS = {
    'one': ((300, 580),),
    'two': ((100, 380), (1200, 1480)),
}
# No chunk boundary falls inside a span (the engine's no-straddle grid,
# `test_gemma_admission_plans_a_no_straddle_chunk_grid`); the tails are
# the step shapes after an image.
SPAN_SPLITS = {
    'one': [580, 1024, L],
    'two': [380, 1200, 1480, 1481, 1485, L],
}


def _span_tensors(spans_per_seq):
  indptr, bounds = [0], []
  for spans in spans_per_seq:
    bounds.extend(spans)
    indptr.append(len(bounds))
  i32 = lambda x: torch.tensor(x, dtype=torch.int32, device='cuda'
                              )  # noqa: E731
  return i32(indptr), i32(bounds).reshape(-1, 2)


def _call_spanned(cache, calls, spans_per_seq):
  from gemma_attn import gemma_attention  # noqa: PLC0415
  q = cache.q(calls)
  meta = cache.meta(calls)
  out = torch.empty_like(q)
  si, sb = _span_tensors(spans_per_seq)
  gemma_attention(q, cache.pages, *meta, cache.g['window_left'], out,
                  span_indptr=si, span_bounds=sb)
  torch.cuda.synchronize()
  return out


def _spanned_allowed(start, end, lo, spans):
  """The predicate: AND(window, OR(causal, same span)), window the
  outer clause on both disjuncts (DOC#VISION-GEMMA)."""
  pos = torch.arange(start, end, device='cuda')[:, None]
  key = torch.arange(lo, end, device='cuda')[None, :]
  block = torch.zeros_like(pos, dtype=torch.bool) | torch.zeros_like(
      key, dtype=torch.bool)
  for a, b in spans:
    block |= (pos >= a) & (pos < b) & (key >= a) & (key < b)
  return ((key <= pos) | block) & (key >= pos - (WINDOW - 1))


def spanned_reference_rows(cache, si, start, end, spans):
  g = cache.g
  nkv, d = g['kv_heads'], g['head_dim']
  group = HEADS // nkv
  lo = max(0, start - (WINDOW - 1))
  k, v = cache.dense_kv(si, lo, end)
  q = cache.seqs[si].q(start, end).float()
  R = end - start
  s = torch.einsum('rhgd,lhd->rhgl', q.view(R, nkv, group, d), k.float())
  allowed = _spanned_allowed(start, end, lo, spans)
  s = s.masked_fill(~allowed[:, None, None, :], float('-inf'))
  o = torch.einsum('rhgl,lhd->rhgd', torch.softmax(s, dim=-1), v.float())
  return o.reshape(R, HEADS, d).to(torch.bfloat16)


def spanned_wheel_rows(cache, si, start, end, spans):
  """The wheel on the engine's exact masked plan: `causal=False`, no
  `window_left`, the predicate bit-packed little-endian over the
  gathered page window (the retired `image_block_mask` form)."""
  from reference import _new_wrapper  # noqa: PLC0415
  if 'w' not in _WHEEL:
    _WHEEL['w'] = _new_wrapper()
  wr = _WHEEL['w']
  g = cache.g
  calls = [(si, end - start, end)]
  qo, kvp, idx, last, base = cache.meta(calls)
  origin = int(base[0])
  allowed = _spanned_allowed(start, end, origin, spans).reshape(-1)
  pad = (-allowed.numel()) % 8
  if pad:
    allowed = torch.cat(
        [allowed, torch.zeros(pad, dtype=torch.bool, device='cuda')])
  bits = allowed.reshape(-1, 8).to(torch.uint8)
  packed = (bits << torch.arange(8, device='cuda', dtype=torch.uint8)).sum(
      1, dtype=torch.uint8)
  wr.plan(qo, kvp, idx, last, HEADS, g['kv_heads'], g['head_dim'], PAGE,
          causal=False, sm_scale=1.0, q_data_type=torch.bfloat16,
          kv_data_type=torch.bfloat16, packed_custom_mask=packed)
  return wr.run(cache.q(calls), cache.pages)


def _assert_spanned_near_fp32(cache, out, si, start, end, spans, label):
  ref = spanned_reference_rows(cache, si, start, end, spans).float()
  wheel = spanned_wheel_rows(cache, si, start, end, spans).float()
  rel = ((out.float() - ref).norm() / ref.norm()).item()
  rel_w = ((wheel - ref).norm() / ref.norm()).item()
  assert rel <= 2.0 * rel_w + 1e-6, (
      f'{label}: rel-L2 vs fp32 {rel:.3e}, the wheel {rel_w:.3e}')


