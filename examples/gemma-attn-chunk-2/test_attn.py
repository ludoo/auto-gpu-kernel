@gpu
@pytest.mark.parametrize('name', list(SPANS))
def test_spanned_chunked_equals_whole(sliding_cache, name):
  """Chunking on the no-straddle grid, every chunk launched with the
  whole prompt's spans (the engine hands every chunk
  `step_ctx.image_spans`), equals the whole spanned call bitwise; the
  1- and 4-row tails after an image are launched with NO spans, as
  decode and verify are, and equal it too."""
  spans = SPANS[name]
  whole_s = _call_spanned(sliding_cache, [(0, L, L)], [spans])
  start = 0
  for end in SPAN_SPLITS[name]:
    rows = end - start
    if rows <= 4:
      out = _call(sliding_cache, [(0, rows, end)])
    else:
      out = _call_spanned(sliding_cache, [(0, rows, end)], [spans])
    _assert_bitwise(out, whole_s[start:end],
                    f'spans {name} chunk [{start}, {end})')
    if rows > 4:
      _assert_spanned_near_fp32(sliding_cache, out, 0, start, end, spans,
                                f'spans {name} chunk [{start}, {end})')
    start = end


