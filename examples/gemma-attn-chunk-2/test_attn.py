@gpu
@pytest.mark.parametrize('rows', [1, 4])
def test_cuda_graph_capture_and_replay(cache, whole, rows):
  """Decode and verify replay under CUDA graphs with the metadata
  buffers rewritten between replays: no host sync, no data-dependent
  host work, the metadata read on device. `kv_indices` is a fixed
  buffer longer than the gather, the served shape."""
  from gemma_attn import gemma_attention  # noqa: PLC0415
  calls = [(0, rows, L - 200)]
  q = cache.q(calls).clone()
  qo, kvp, idx, last, base = cache.meta(calls)
  idx_buf = torch.zeros(4096, dtype=torch.int32, device='cuda')
  idx_buf[:idx.numel()] = idx
  out = torch.empty_like(q)
  wl = cache.g['window_left']
  stream = torch.cuda.Stream()
  with torch.cuda.stream(stream):
    for _ in range(3):
      gemma_attention(q, cache.pages, qo, kvp, idx_buf, last, base, wl, out)
  torch.cuda.current_stream().wait_stream(stream)
  graph = torch.cuda.CUDAGraph()
  with torch.cuda.graph(graph):
    gemma_attention(q, cache.pages, qo, kvp, idx_buf, last, base, wl, out)
  out.zero_()
  graph.replay()
  torch.cuda.synchronize()
  _assert_bitwise(out, whole[L - 200 - rows:L - 200], 'graph replay')
  calls2 = [(0, rows, L)]
  qo2, kvp2, idx2, last2, base2 = cache.meta(calls2)
  q.copy_(cache.q(calls2))
  kvp.copy_(kvp2)
  idx_buf[:idx2.numel()] = idx2
  last.copy_(last2)
  base.copy_(base2)
  graph.replay()
  torch.cuda.synchronize()
  _assert_bitwise(out, whole[L - rows:], 'graph replay, rewritten metadata')


