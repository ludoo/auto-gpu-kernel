def test_spanned_whole_near_fp32(sliding_cache, name):
  spans = SPANS[name]
  out = _call_spanned(sliding_cache, [(0, L, L)], [spans])
  _assert_spanned_near_fp32(sliding_cache, out, 0, 0, L, spans,
                            f'spans {name} whole')
  # The block is load-bearing: the spanned rows differ from causal.
  ref = spanned_reference_rows(sliding_cache, 0, 0, L, spans).float()
  ref0 = reference_rows(sliding_cache, 0, 0, L).float()
  lo, hi = spans[0]
  gap = ((ref[lo:hi] - ref0[lo:hi]).norm() / ref[lo:hi].norm()).item()
  assert gap > 1e-3, f'spans {name}: image block not load-bearing: {gap:.3e}'


