"""The contract of gemma's paged causal attention kernel (gemma_attn.py),
verbatim sparkle's own gate `tests/test_gemma_attention_gpu.py` with the
imports pointed here. Two-sided:

1. Invariance, BITWISE. A row's output bytes do not depend on how the
   engine computed it. Every row of a 1600-position sequence per kind
   is computed (a) in one whole call, (b) in chunks at the splits
   {700 | 1025 | 512+1024 | 1536+1 | 1536+4}, (c) one row at a time at
   its own kv_len (decode), (d) in 4-row calls (verify), (e) in 1-,
   2-, 3-row calls (eager verify); and under n = 2 sequences in one
   launch. All equal to (a), bytes. The same for the last 64 rows at
   kv 32k and 128k. There is no tolerance and none may be introduced.
2. Correctness, within bf16 rounding of an fp32 reference: on every
   arm the kernel's rel-L2 distance from `reference_rows` is at most
   twice the wheel's own distance (+1e-6), the bound the M-invariant
   linear holds. The wheel (FlashInfer's paged prefill on the engine's
   exact plan) is the comparator, not the contract.

Plus determinism over 8 calls, CUDA-graph capture and replay at rows
1 and 4 with the metadata buffers rewritten between replays (the
served decode and verify shape: `kv_indices` a fixed buffer longer
than the gather, so the split path launches its max block count), and
no torch attention / matmul / softmax / compile on the path.

Synthetic tensors, no checkpoint, no service conflict.

Do not edit this file; a candidate that needs it changed is wrong.
"""

